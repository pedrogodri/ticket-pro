#!/usr/bin/env bash
# Tests scripts/sync-shared.sh against a throwaway fixture repository (ADR-0017).
# Usage: scripts/tests/sync-shared.test.sh
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
script="$here/../sync-shared.sh"
fx="$(mktemp -d "${TMPDIR:-/tmp}/sync-shared-test.XXXXXX")"
trap 'rm -rf "${fx:?}"' EXIT

failures=0
pass() { echo "ok    $1"; }
fail() { echo "FAIL  $1"; failures=$((failures + 1)); }
check() { # description, command...
  local desc="$1"; shift
  if "$@" >/dev/null 2>&1; then pass "$desc"; else fail "$desc"; fi
}

# ---------- fixture ----------
mkdir -p "$fx/scripts" "$fx/shared/go/retry/testdata" "$fx/shared/go/envelope" "$fx/shared/go/internal/testenv" \
  "$fx/shared/dotnet/src/Messaging" "$fx/contracts/events/Ping/" "$fx/contracts/events/Pong" "$fx/contracts/examples" \
  "$fx/services/a" "$fx/services/b/src/B" "$fx/services/c"
echo "0.1.0" > "$fx/shared/go/VERSION"
echo "0.1.0" > "$fx/shared/dotnet/VERSION"
echo "0.1.0" > "$fx/contracts/VERSION"
cat > "$fx/shared/go/retry/retry.go" <<'EOF'
// Package retry is a fixture.
package retry

import "github.com/ticketpro/platform/envelope"

// Use keeps the import alive.
var Use = envelope.Name
EOF
cat > "$fx/shared/go/envelope/envelope.go" <<'EOF'
package envelope

// Name is a fixture.
const Name = "envelope"
EOF
echo 'package retry' > "$fx/shared/go/retry/retry_test.go"
echo 'fixture' > "$fx/shared/go/retry/testdata/data.txt"
echo 'package testenv' > "$fx/shared/go/internal/testenv/testenv.go"
echo 'namespace TicketPro.Platform.Messaging; public static class X { }' > "$fx/shared/dotnet/src/Messaging/X.cs"
mkdir -p "$fx/shared/dotnet/src/obj"
echo 'namespace Junk; class Y { }' > "$fx/shared/dotnet/src/obj/Y.cs"
echo '{"$id":"envelope"}' > "$fx/contracts/envelope.schema.json"
echo '{"$id":"common"}' > "$fx/contracts/common.schema.json"
echo '{"x-producer":"a","x-consumers":["b"]}' > "$fx/contracts/events/Ping/v1.schema.json"
echo '{"x-producer":"b","x-consumers":["c"]}' > "$fx/contracts/events/Pong/v1.schema.json"
echo '{"type":"Ping"}' > "$fx/contracts/examples/Ping.v1.json"
echo '{"type":"Pong"}' > "$fx/contracts/examples/Pong.v1.json"
cat > "$fx/scripts/sync-shared.conf" <<'EOF'
# kind  service  module-or-project
go      a        github.com/ticketpro/a
dotnet  b        B
EOF
(cd "$fx" && git init -q && git add -A && git -c user.email=t@t -c user.name=t commit -qm fixture)

sync() { "$script" --root "$fx" "$@"; }

# ---------- 1st sync ----------
if ! sync >"$fx/.out" 2>&1; then cat "$fx/.out"; fail "first sync exits 0"; fi

go_copy="$fx/services/a/internal/platform/retry/retry.go"
check "1. go file copied" test -f "$go_copy"
check "1. go header first line" sh -c "head -1 '$go_copy' | grep -qxF '// Code generated by scripts/sync-shared.sh from shared/go@0.1.0. DO NOT EDIT.'"
check "1. go import rewritten" grep -q '"github.com/ticketpro/a/internal/platform/envelope"' "$go_copy"
check "1. go import no longer points at shared module" sh -c "! grep -q 'ticketpro/platform/' '$go_copy'"
check "2. no _test.go copied" sh -c "! find '$fx/services/a' -name '*_test.go' | grep -q ."
check "2. no testdata copied" test ! -e "$fx/services/a/internal/platform/retry/testdata"
check "2. no internal helpers copied" test ! -e "$fx/services/a/internal/platform/internal"
check "3. go .vendored.json" sh -c "jq -e '.source == \"shared/go\" and .version == \"0.1.0\" and (.sha256 | test(\"^[0-9a-f]{64}\$\"))' '$fx/services/a/internal/platform/.vendored.json'"
cs_copy="$fx/services/b/src/B/Platform/Messaging/X.cs"
check "4. cs file copied under project" test -f "$cs_copy"
check "4. cs auto-generated header" sh -c "head -1 '$cs_copy' | grep -qxF '// <auto-generated>' && grep -q 'DO NOT EDIT' '$cs_copy' && grep -qxF '// </auto-generated>' '$cs_copy'"
check "4. bin/obj sources ignored" test ! -e "$fx/services/b/src/B/Platform/obj"
check "5. a gets Ping schema" test -f "$fx/services/a/contracts/events/Ping/v1.schema.json"
check "5. a does not get Pong" test ! -e "$fx/services/a/contracts/events/Pong"
check "5. b gets Ping and Pong" sh -c "test -f '$fx/services/b/contracts/events/Ping/v1.schema.json' && test -f '$fx/services/b/contracts/events/Pong/v1.schema.json'"
check "5. c gets only Pong + examples" sh -c "test -f '$fx/services/c/contracts/examples/Pong.v1.json' && test ! -e '$fx/services/c/contracts/examples/Ping.v1.json'"
check "5. envelope/common vendored" sh -c "test -f '$fx/services/c/contracts/envelope.schema.json' && test -f '$fx/services/c/contracts/common.schema.json'"
check "5. json copied verbatim" cmp -s "$fx/contracts/events/Ping/v1.schema.json" "$fx/services/a/contracts/events/Ping/v1.schema.json"
check "5. contracts .vendored.json source" sh -c "jq -e '.source == \"contracts\" and .version == \"0.1.0\"' '$fx/services/c/contracts/.vendored.json'"

# ---------- idempotency ----------
(cd "$fx" && git add -A && git -c user.email=t@t -c user.name=t commit -qm synced)
sync >/dev/null 2>&1
check "6. second sync leaves no diff" sh -c "test -z \"\$(cd '$fx' && git status --porcelain)\""
check "7. --check passes when in sync" sync --check

# ---------- drift detection ----------
printf ' ' >> "$go_copy"
if sync --check >"$fx/.out" 2>&1; then fail "8. --check fails after hand edit"; else pass "8. --check fails after hand edit"; fi
check "8. --check names the edited path" grep -q 'internal/platform/retry/retry.go' "$fx/.out"
sync >/dev/null 2>&1

rm "$fx/shared/go/envelope/envelope.go"
cat > "$fx/shared/go/retry/retry.go" <<'EOF'
// Package retry is a fixture.
package retry
EOF
if sync --check >/dev/null 2>&1; then fail "9. --check fails after source removal"; else pass "9. --check fails after source removal"; fi
sync >/dev/null 2>&1
check "9. sync removes the orphan" test ! -e "$fx/services/a/internal/platform/envelope/envelope.go"

echo "0.2.0" > "$fx/shared/go/VERSION"
if sync --check >/dev/null 2>&1; then fail "10. --check fails after VERSION bump"; else pass "10. --check fails after VERSION bump"; fi

echo
if [ "$failures" -eq 0 ]; then echo "sync-shared tests: all passed"; else echo "sync-shared tests: $failures failed"; exit 1; fi
